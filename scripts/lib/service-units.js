'use strict';

// The pure part of scripts/qwctl.js: names, the options file (/etc/qemuweb/<name>.args) and the systemd units
// (templates in deploy/systemd/). Nothing here reads /etc, runs a command or prints.
const fs = require('fs');
const path = require('path');
const {parseArguments, UsageError} = require('../../common/cli');
const {serverSpec} = require('../../server/options');
const {runnerSpec, runSpec} = require('../../runner/options');
const {serverRuntime} = require('../../common/runtime-dir');
const {tokenFilePath} = require('../../common/local-token');
const {DEFAULT_ADDRESS, runnerHost} = require('../../common/bind');

const UNIT_DIRECTORY = '/etc/systemd/system';
const CONFIG_DIRECTORY = '/etc/qemuweb';
const STATE_DIRECTORY = '/var/lib/qemuweb';
const LOG_DIRECTORY = '/var/log/qemuweb';
const MARKER = '# Generated by QemuWeb (scripts/qwctl.sh install): do not edit (a drop-in survives: systemctl edit).';
const NAME = /^[a-z0-9][a-z0-9-]{0,15}$/;
const ACCOUNT = /^[A-Za-z0-9_][A-Za-z0-9_.@-]*$/;

// What systemd would split, unquote or expand in the value of ARGS (an EnvironmentFile line, then $ARGS split into words):
// refused, never quoted. A % is not special there (only in a unit, see escapeUnit).
const UNSAFE = /[\s"'`\\$\x00-\x1f\x7f]/;
const UNSAFE_TEXT = 'a space, a quote, a backquote, a backslash, a $ or a control character (systemd would split or change it)';

// The options that a service never takes, with the reason.
const FORBIDDEN = {
  server: {'--no-auth': 'a service always authenticates its users', '--ephemeral': 'it is for the test scenarios'},
  local: {
    '--exit-on-disconnect': 'a service keeps its machines and reconnects',
    '--port': 'it comes from --listen in server.args', '--host': 'it comes from --bind in server.args',
    '--token-file': 'it comes from --runtime in server.args'
  },
  remote: {'--url': 'it stays in the runner file', '--ca': 'it stays in the runner file', '--exit-on-disconnect': 'a service keeps its machines and reconnects'}
};

// A service: {target: server|runner, mode: server|local|remote, name: null|NAME, base, unit}.
function service(target, {name = null, remote = false} = {}) {
  const base = target === 'server' ? 'server' : name ? `runner-${name}` : 'runner';
  return {target, name, mode: target === 'server' ? 'server' : remote ? 'remote' : 'local', base, unit: `qemuweb-${base}`};
}
const unitPath = item => path.join(UNIT_DIRECTORY, `${item.unit}.service`);
const argsPath = item => path.join(CONFIG_DIRECTORY, `${item.base}.args`);

// The service of a unit file name, or null. The mode of a runner comes from the content of the unit (unitInfo).
function serviceOfFile(file) {
  const match = /^qemuweb-(server|runner(?:-([a-z0-9][a-z0-9-]{0,15}))?)\.service$/.exec(file);
  if (!match) return null;
  return match[1] === 'server' ? service('server') : service('runner', {name: match[2] || null});
}

const programSpec = (mode, root) => ({server: serverSpec, local: runnerSpec, remote: runSpec})[mode](root);

// The words of a program, validated with its own option table: {settings, words: Map flag -> value (true for a flag)}.
// Paths are made absolute, or with `fromFile` must be: a relative one would depend on the directory of qwctl.sh. Throws a UsageError.
function checkWords(mode, root, words, {fromFile = false} = {}) {
  for (const word of words) {
    if (word.startsWith('--') && Object.hasOwn(FORBIDDEN[mode], word)) throw new UsageError(`${word} is not accepted here: ${FORBIDDEN[mode][word]}`);
  }
  const spec = programSpec(mode, root);
  // parseArguments takes these two as a request for help and checks nothing else.
  for (const word of words) if (word === '-h' || word === '--help') throw new UsageError(`Unknown option: ${word}`);
  const {settings} = parseArguments(spec, words);
  const map = new Map();
  for (let index = 0; index < words.length; index++) {
    const option = spec.options.find(item => item.flag === words[index]);
    if (!option.metavar) { map.set(option.flag, true); continue; }
    const raw = words[++index];
    if (fromFile && option.kind === 'path' && !path.isAbsolute(raw)) throw new UsageError(`${option.flag} must be an absolute path: ${raw}`);
    const value = option.kind === 'path' ? path.resolve(raw) : raw;
    if (UNSAFE.test(value)) throw new UsageError(`The value of ${option.flag} contains ${UNSAFE_TEXT}: ${JSON.stringify(value)}`);
    map.set(option.flag, value);
  }
  return {settings, words: map};
}

const wordsOf = map => [...map].flatMap(([flag, value]) => (value === true ? [flag] : [flag, value]));

// The text of a new options file.
function formatArgs(item, map) {
  return [
    `# Options of ${item.unit}, read by systemd (EnvironmentFile). Written once by scripts/qwctl.sh, never overwritten: edit it here.`,
    '# One line, ARGS=OPTIONS, without quotes; a value holds no space, quote, backslash or dollar sign. Then: scripts/qwctl.sh restart',
    `ARGS=${wordsOf(map).join(' ')}`,
    ''
  ].join('\n');
}

// The words of an options file. Throws an Error that says what is wrong.
function parseArgs(text, file) {
  const lines = text.split('\n').map(line => line.trim()).filter(line => line && !/^[#;]/.test(line));
  if (lines.length !== 1 || !lines[0].startsWith('ARGS=')) throw new Error(`${file}: expected exactly one line ARGS=OPTIONS (and comments).`);
  const words = lines[0].slice('ARGS='.length).split(/[ \t]+/).filter(Boolean);
  const bad = words.find(word => UNSAFE.test(word));
  if (bad) throw new Error(`${file}: ${JSON.stringify(bad)} contains ${UNSAFE_TEXT}.`);
  return words;
}

// The checked content of an options file, or an Error that names it.
function readArgs(mode, root, text, file) {
  const words = parseArgs(text, file);
  try { return checkWords(mode, root, words, {fromFile: true}); }
  catch (error) {
    if (error instanceof UsageError) throw new Error(`${file}: ${error.message}`);
    throw error;
  }
}

// The options of a new options file: the given ones, completed with the defaults. `home` is the home directory of the
// account, `fileRuntime` the runtime of the remote runner's file, which wins over the default (never contradicted).
function withDefaults(item, map, {home = null, fileRuntime = null} = {}) {
  const defaults = new Map();
  if (item.mode === 'server') {
    defaults.set('--listen', '3002').set('--local-runner', true).set('--runtime', path.join(STATE_DIRECTORY, 'server'))
      .set('--users', path.join(CONFIG_DIRECTORY, 'users.json')).set('--runners', path.join(CONFIG_DIRECTORY, 'runners.json'))
      .set('--logs', LOG_DIRECTORY);
  } else {
    if (item.mode === 'remote') defaults.set('--runner-config', defaultRunnerFile(item, home));
    if (!fileRuntime) defaults.set('--runtime', path.join(STATE_DIRECTORY, item.base));
  }
  return new Map([...defaults, ...map]);
}

const defaultRunnerFile = (item, home) => path.join(home, '.config', 'qemuweb-runner', item.name ? `${item.name}.json` : 'runner.json');

// The options of the local runner that come from the server's options (the address rule is common/bind.js).
function serverLink(serverSettings, identity) {
  const runtime = serverSettings.given.has('--runtime') ? serverSettings.runtime : serverRuntime(serverSettings.port, {identity});
  const host = runnerHost(serverSettings.bind);
  return ['--port', String(serverSettings.port), ...(host === DEFAULT_ADDRESS ? [] : ['--host', host]), '--token-file', tokenFilePath(runtime)];
}

// In a unit, % starts a specifier.
const escapeUnit = text => text.replaceAll('%', '%%');

// The text of a unit. `link` is serverLink() for a local runner.
function renderUnit(item, {root, sysuser, link = []}) {
  for (const [what, text] of [['The directory of QemuWeb', root], ['The account', sysuser], ...link.map(word => ['An option of the server', word])]) {
    if (UNSAFE.test(text)) throw new Error(`${what} (${JSON.stringify(text)}) contains ${UNSAFE_TEXT}.`);
  }
  const template = item.mode === 'server' ? 'qemuweb-server' : `qemuweb-runner-${item.mode}`;
  const values = {MARKER, ROOT: escapeUnit(root), SYSUSER: escapeUnit(sysuser), ARGS_FILE: argsPath(item), SERVER_LINK: link.map(escapeUnit).join(' ')};
  return fs.readFileSync(path.join(__dirname, '..', '..', 'deploy', 'systemd', `${template}.service.in`), 'utf8')
    .replace(/@([A-Z_]+)@/g, (all, key) => values[key]);
}

// What an installed unit says: {generated, sysuser, mode, words (of ExecStart, after the program), usesArgs}.
function unitInfo(item, text) {
  const value = key => [...text.matchAll(new RegExp(`^\\s*${key}=(.*)$`, 'gm'))].map(match => match[1].trim()).filter(Boolean).at(-1) || '';
  const all = value('ExecStart').split(/\s+/).map(word => word.replaceAll('%%', '%'));
  const program = all.findIndex(word => /(?:scripts\/(?:runner|server)\.sh|(?:runner|server)\/main\.js)$/.test(word));
  const words = all.slice(program + 1);
  const mode = item.target === 'server' ? 'server' : words[0] === 'run' ? 'remote' : 'local';
  if (mode === 'remote') words.shift();
  return {generated: text.startsWith(MARKER), sysuser: value('User') || 'root', mode, words: words.filter(word => word !== '$ARGS'), usesArgs: words.includes('$ARGS')};
}

// The last value of an option in words that were not validated (a unit this program did not generate).
function rawOption(words, flag) {
  const index = words.lastIndexOf(flag);
  return index >= 0 && index + 1 < words.length ? words[index + 1] : null;
}

module.exports = {UNIT_DIRECTORY, CONFIG_DIRECTORY, STATE_DIRECTORY, LOG_DIRECTORY, MARKER, NAME, ACCOUNT, service, unitPath, argsPath, serviceOfFile, programSpec,
  checkWords, formatArgs, parseArgs, readArgs, withDefaults, defaultRunnerFile, serverLink, renderUnit, unitInfo, rawOption};
